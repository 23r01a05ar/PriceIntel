-- Migration: Initialize Phase 4 Schema 

-- 1. Profiles Table (To extend Supabase Auth with custom user data)
CREATE TABLE profiles (
    id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
    username VARCHAR(80) UNIQUE,
    bio VARCHAR(500),
    whatsapp_no VARCHAR(20),
    twitter_handle VARCHAR(100),
    facebook_url VARCHAR(255),
    instagram_url VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Products Table
CREATE TABLE products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(100),
    image_url TEXT
);
CREATE INDEX idx_products_name ON products(name);

-- 3. Prices Table
CREATE TABLE prices (
    price_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES products(product_id) ON DELETE CASCADE NOT NULL,
    store_name VARCHAR(100) NOT NULL,
    price FLOAT NOT NULL,
    timestamp TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    product_url TEXT
);

-- 4. Search History Table
CREATE TABLE search_history (
    search_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    query VARCHAR(255) NOT NULL,
    timestamp TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. Price Alerts Table
CREATE TABLE price_alerts (
    alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    product_name VARCHAR(255) NOT NULL,
    target_price FLOAT NOT NULL,
    user_email VARCHAR(120) NOT NULL,
    is_active BOOLEAN DEFAULT TRUE,
    timestamp TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    last_notified_at TIMESTAMP WITH TIME ZONE,
    notification_status VARCHAR(50) DEFAULT 'PENDING',
    retry_count INTEGER DEFAULT 0
);
CREATE INDEX idx_price_alerts_email ON price_alerts(user_email);

-- 6. Wishlist Table
CREATE TABLE wishlist (
    wish_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    product_title VARCHAR(255) NOT NULL,
    price VARCHAR(50),
    store VARCHAR(100),
    product_url TEXT,
    image_url TEXT,
    timestamp TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
